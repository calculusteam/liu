/*
 * Build a one-line list title from the first user-authored prompt text. Skip
 * CLI wrappers, environment metadata, and imported-session markers; unwrap tags
 * that carry the prompt and ignore messages emitted on the user's behalf.
 */
#ifndef HISTORY_SESSION_TITLE_H
#define HISTORY_SESSION_TITLE_H

#include "core/types.h"

#include <stdio.h>
#include <string.h>

/* Bytes, NUL included. A palette row shows far fewer; the rest is searchable. */
#define CHAT_SESSION_TITLE_CAP 160

static inline bool chat_title_starts(const char *s, const char *prefix) {
    return strncmp(s, prefix, strlen(prefix)) == 0;
}

/* True when `s` (white space already skipped, read up to `end` when that is
 * not NULL) is something a CLI wrote on the user's behalf, or nothing. */
static inline bool chat_prompt_is_wrapper_at(const char *s, const char *end) {
    if (!s || !*s || (end && s >= end)) return true;
    if (*s == '<') {
        unsigned char c = (unsigned char)s[1];
        if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || c == '/' || c == '!' || c == '?') return true;
    }
    return chat_title_starts(s, "Caveat: The messages below were generated by the user") ||
           chat_title_starts(s, "This session is being continued from a previous conversation") ||
           chat_title_starts(s, "[Request interrupted") ||
           /* Liu's own note at the head of a session it carried over from
            * another agent (history/bridge/writers): provenance, not a prompt. */
           chat_title_starts(s, "[Imported into ");
}

static inline const char *chat_title_skip_space(const char *s, const char *end) {
    while (*s && (!end || s < end) && ((unsigned char)*s <= 0x20 || *s == 0x7f)) s++;
    return s;
}

/* Some CLIs do not wrap the prompt AWAY, they carry it IN a tag:
 *   <user_query>…</user_query>        Cursor-family, Grok
 *   <user_input mode="act">…</user_input>   Cline's CLI
 *   <task>…</task>                    Cline, Roo, Kilo
 *   <user_message>…</user_message>
 * and Claude Code puts a paste in front of what was typed:
 *   <pasted_content …>…</pasted_content> the prompt
 * Returns where the prompt starts, with `*end` at the carrier's close (NULL =
 * to the end of the text). NULL when what is left is a wrapper. */
static inline const char *chat_title_prompt_span(const char *text, const char **end) {
    static const char *const carriers[] = { "user_query", "user_input", "task", "user_message" };
    *end = NULL;
    if (!text) return NULL;
    const char *p = text;
    for (int depth = 0; depth < 6; depth++) {
        p = chat_title_skip_space(p, *end);
        if (*p == '<') {
            bool stepped = false;
            for (usize i = 0; i < sizeof carriers / sizeof carriers[0] && !stepped; i++) {
                usize n = strlen(carriers[i]);
                if (strncmp(p + 1, carriers[i], n) != 0 || (p[1 + n] != '>' && p[1 + n] != ' ')) continue;
                const char *open_end = strchr(p, '>');
                if (!open_end || (*end && open_end >= *end)) return NULL;
                char closing[32];
                snprintf(closing, sizeof closing, "</%s>", carriers[i]);
                const char *close = strstr(open_end + 1, closing);
                if (close && (!*end || close < *end)) *end = close;
                p = open_end + 1;
                stepped = true;
            }
            if (stepped) continue;
            if (chat_title_starts(p, "<pasted_content")) {
                const char *close = strstr(p, "</pasted_content>");
                if (!close || (*end && close >= *end)) return NULL;
                p = close + strlen("</pasted_content>");
                continue;
            }
        }
        break;
    }
    p = chat_title_skip_space(p, *end);
    return chat_prompt_is_wrapper_at(p, *end) ? NULL : p;
}

static inline bool chat_prompt_is_wrapper(const char *text) {
    const char *end;
    return chat_title_prompt_span(text, &end) == NULL;
}

/* `text` as one line in `out`: control bytes and runs of white space become
 * one space, both ends trimmed, cut on a code-point boundary with "…" when it
 * does not fit. Returns false (and an empty `out`) for a wrapper. */
static inline bool chat_title_from_prompt(const char *text, char *out, usize cap) {
    if (cap) out[0] = '\0';
    if (cap < 8) return false;
    const char *end = NULL;
    const unsigned char *p = (const unsigned char *)chat_title_prompt_span(text, &end);
    if (!p) return false;
    const unsigned char *stop = (const unsigned char *)end;
    usize o = 0;
    bool gap = false, cut = false;
    while (*p && (!stop || p < stop)) {
        if (*p <= 0x20 || *p == 0x7f) { gap = o > 0; p++; continue; }
        /* The whole sequence or none of it. */
        usize n = (*p < 0x80) ? 1 : (*p >> 5) == 0x6 ? 2 : (*p >> 4) == 0xe ? 3 : (*p >> 3) == 0x1e ? 4 : 1;
        for (usize k = 1; k < n; k++)
            if ((p[k] & 0xc0) != 0x80) { n = 1; break; }      /* a broken sequence goes byte by byte */
        if (n == 1 && *p >= 0x80) { p++; continue; }          /* a stray byte: dropped */
        if (o + (gap ? 1 : 0) + n + 4 > cap) { cut = true; break; }   /* room for "…" and the NUL */
        if (gap) { out[o++] = ' '; gap = false; }
        memcpy(out + o, p, n);
        o += n;
        p += n;
    }
    if (cut) { memcpy(out + o, "\xe2\x80\xa6", 3); o += 3; }
    out[o] = '\0';
    return o > 0;
}

#endif /* HISTORY_SESSION_TITLE_H */
