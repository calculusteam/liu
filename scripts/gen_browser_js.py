"""Embed the checked-in browser scripts without a build-time JS dependency."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1] / "src/browser"
for name in ("pick_element", "browser_chrome", "browser_gesture"):
    symbol = "BROWSER_" + name.upper() + "_JS" if name == "pick_element" else name.upper() + "_JS"
    guard = symbol + "_H"
    lines = (root / (name + ".js")).read_text().splitlines(keepends=True)
    body = "\n".join("    " + json.dumps(line, ensure_ascii=False) for line in lines)
    (root / (name + "_js.h")).write_text(
        f"/* Generated by scripts/gen_browser_js.py from {name}.js. */\n"
        f"#ifndef {guard}\n#define {guard}\nstatic const char {symbol}[] =\n{body};\n#endif /* {guard} */\n")
