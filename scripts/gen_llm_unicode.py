#!/usr/bin/env python3
"""Generate the Unicode 16.0 categories used by the byte-BPE pretokenizers."""
import argparse
from pathlib import Path
import unicodedata

parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if unicodedata.unidata_version != '16.0.0':
    raise SystemExit('Generation requires Python with Unicode 16.0.0')
flags = {'L': 1, 'M': 2, 'N': 4, 'P': 8, 'S': 16}
# Unicode White_Space, unlike str.isspace() which includes U+001C..U+001F.
spaces = set(range(9, 14)) | {0x20, 0x85, 0xa0, 0x1680, 0x2028, 0x2029, 0x202f, 0x205f, 0x3000} | set(range(0x2000, 0x200b))
ranges = []
for cp in range(0x110000):
    f = flags.get(unicodedata.category(chr(cp))[0], 0) | (32 if cp in spaces else 0)
    if not f:
        continue
    if ranges and ranges[-1][1] + 1 == cp and ranges[-1][2] == f:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, f])
text = '''/* Generated by scripts/gen_llm_unicode.py; Unicode 16.0.0.
 * General_Category L/M/N/P/S and White_Space. No locale or runtime tables. */
#ifndef LLM_UNICODE_CATEGORIES_H
#define LLM_UNICODE_CATEGORIES_H
#include "core/types.h"
enum { LLM_U_L = 1, LLM_U_M = 2, LLM_U_N = 4, LLM_U_P = 8,
       LLM_U_S = 16, LLM_U_SPACE = 32 };
typedef struct { u32 lo, hi; u8 flags; } LlmUnicodeRange;
static const LlmUnicodeRange llm_unicode_ranges[] = {
'''
text += ''.join(f'    {{0x{lo:X}, 0x{hi:X}, {f}}},\n' for lo, hi, f in ranges)
text += '''};
static inline u8 llm_unicode_flags(u32 cp) {
    usize lo = 0, hi = sizeof llm_unicode_ranges / sizeof *llm_unicode_ranges;
    while (lo < hi) {
        usize mid = lo + (hi - lo) / 2;
        const LlmUnicodeRange *r = &llm_unicode_ranges[mid];
        if (cp < r->lo) hi = mid;
        else if (cp > r->hi) lo = mid + 1;
        else return r->flags;
    }
    return 0;
}
#endif
'''
path = Path(__file__).resolve().parents[1] / 'src/llm/llm_unicode_categories.h'
if args.check:
    if not path.exists() or path.read_text() != text:
        raise SystemExit('Unicode table is stale')
else:
    path.write_text(text)
print(f'{len(ranges)} Unicode category ranges')
