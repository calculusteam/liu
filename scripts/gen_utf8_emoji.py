#!/usr/bin/env python3
"""Regenerate src/core/utf8_emoji.h — the cell width and emoji tables.

utf8_char_width() gives two columns to exactly the codepoints East Asian Width
calls Wide or Fullwidth, and utf8_is_emoji() calls a codepoint an emoji from
the emoji properties, so the grid counts what a program's wcwidth counts.

    python3 scripts/gen_utf8_emoji.py <emoji-data.txt>           # rewrite the header
    python3 scripts/gen_utf8_emoji.py <emoji-data.txt> --check   # verify it is up to date

East Asian Width comes from Python's unicodedata; emoji-data.txt must be the
same Unicode version (https://www.unicode.org/Public/<version>/ucd/emoji/).

Three tables:
  wide        East_Asian_Width W or F.
  emoji       Emoji_Presentation=Yes: drawn in colour, two columns.
  text emoji  Emoji=Yes, Emoji_Presentation=No, above U+1F000: one column like
              text, drawn in colour because no text face on the system has
              them; with VS16 they join a cluster and take two columns.
"""
import sys, unicodedata, pathlib

HDR = pathlib.Path(__file__).resolve().parent.parent / "src" / "core" / "utf8_emoji.h"


def merge(cps):
    out = []
    for cp in sorted(cps):
        if out and cp == out[-1][1] + 1:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def emoji_props(path):
    props = {}
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        rng, prop = [x.strip() for x in line.split(";")[:2]]
        lo, _, hi = rng.partition("..")
        lo = int(lo, 16)
        hi = int(hi, 16) if hi else lo
        props.setdefault(prop, set()).update(range(lo, hi + 1))
    return props


def table(name, rs, what):
    lines = ["/* %s: %d ranges. */" % (what, len(rs)),
             "static const Utf8Range %s[] = {" % name]
    for lo, hi in rs:
        lines.append("    { 0x%05X, 0x%05X }," % (lo, hi))
    lines.append("};")
    return "\n".join(lines)


def render(emoji_data):
    props = emoji_props(emoji_data)
    wide = set()
    for cp in range(0x80, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        if unicodedata.east_asian_width(chr(cp)) in ("W", "F"):
            wide.add(cp)
    # Unassigned code points in these blocks default to W (EastAsianWidth.txt);
    # planes 2 and 3 are left to utf8.c, which gives the whole planes two columns.
    for lo, hi in ((0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF)):
        wide.update(range(lo, hi + 1))
    pres = props["Emoji_Presentation"]
    text = {cp for cp in props["Emoji"] - pres if cp >= 0x1F000}
    body = [
        "/*",
        " * Liu — cell widths and emoji properties.",
        " *",
        " * GENERATED by scripts/gen_utf8_emoji.py from Unicode %s (East Asian Width)" % unicodedata.unidata_version,
        " * and its emoji-data.txt. Do not edit by hand; re-run the script (it has a",
        " * --check mode) instead. Each table is sorted and non-overlapping, so it is",
        " * binary-searched.",
        " */",
        "#ifndef LIU_UTF8_EMOJI_H",
        "#define LIU_UTF8_EMOJI_H",
        "",
        '#include "core/types.h"',
        "",
        "typedef struct { u32 lo, hi; } Utf8Range;",
        "",
        table("g_utf8_wide_ranges", merge(wide), "East_Asian_Width W or F"),
        "",
        table("g_utf8_emoji_pres_ranges", merge(pres), "Emoji_Presentation=Yes"),
        "",
        table("g_utf8_emoji_text_ranges", merge(text),
              "Emoji=Yes and Emoji_Presentation=No, from U+1F000"),
        "",
        "static inline bool utf8_range_find(const Utf8Range *r, u32 n, u32 cp) {",
        "    u32 lo = 0, hi = n;",
        "    while (lo < hi) {",
        "        u32 mid = (lo + hi) / 2;",
        "        if (cp < r[mid].lo) hi = mid;",
        "        else if (cp > r[mid].hi) lo = mid + 1;",
        "        else return true;",
        "    }",
        "    return false;",
        "}",
        "",
        "#define UTF8_RANGE_COUNT(t) ((u32)(sizeof(t) / sizeof((t)[0])))",
        "",
        "#endif",
        "",
    ]
    return "\n".join(body)


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    if len(args) != 1:
        sys.exit("usage: gen_utf8_emoji.py <emoji-data.txt> [--check]")
    text = render(args[0])
    if "--check" in sys.argv[1:]:
        if HDR.read_text() != text:
            sys.exit("%s is out of date: re-run scripts/gen_utf8_emoji.py" % HDR)
        print("up to date")
        return
    HDR.write_text(text)
    print("wrote", HDR)


if __name__ == "__main__":
    main()
