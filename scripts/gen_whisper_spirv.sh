#!/usr/bin/env bash
#
# Compile src/voice/shaders/*.comp to SPIR-V and embed the result in
# src/voice/whisper_vulkan_spv.h.
#
# The header is CHECKED IN and this script is run by hand, the same way
# src/browser/pick_element_js.h is generated. The alternative — compiling at
# build time — would make glslc a hard dependency of every build of a terminal
# emulator, on every platform, for a backend most users never touch. Re-run
# after editing any shader.
#
# Needs glslc (brew install shaderc / apt install glslc).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/src/voice/shaders"
OUT="$ROOT/src/voice/whisper_vulkan_spv.h"

if ! command -v glslc >/dev/null 2>&1; then
    echo "error: glslc not found (brew install shaderc / apt install glslc)" >&2
    exit 1
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# vulkan1.0 on purpose: it is the baseline every driver this backend targets
# implements, and nothing here needs a later feature level.
names=()
for f in "$SRC"/*.comp; do
    n="$(basename "$f" .comp)"
    glslc --target-env=vulkan1.0 -O -I "$SRC" -o "$TMP/$n.spv" "$f"
    names+=("$n")
done

python3 - "$OUT" "$TMP" "${names[@]}" <<'PY'
import struct, sys, os

out_path, tmp = sys.argv[1], sys.argv[2]
names = sys.argv[3:]

lines = ["""/*
 * Liu - SPIR-V modules for the Vulkan Whisper backend.
 *
 * GENERATED by scripts/gen_whisper_spirv.sh from the .comp files in
 * src/voice/shaders. A literal glob is avoided here: it closes this comment.
 * Do not edit; re-run that script after changing a shader.
 *
 * Checked in rather than compiled at build time so glslc is not a dependency
 * of an ordinary build. Each blob is a u32 array because SPIR-V is a stream of
 * 32-bit words and vkCreateShaderModule requires 4-byte alignment — a char
 * array would not guarantee it.
 */
#ifndef VOICE_WHISPER_VULKAN_SPV_H
#define VOICE_WHISPER_VULKAN_SPV_H

#include "core/types.h"
"""]

for n in names:
    data = open(os.path.join(tmp, n + ".spv"), "rb").read()
    words = struct.unpack("<%dI" % (len(data) // 4), data)
    lines.append("static const u32 WV_SPV_%s[] = {" % n)
    for i in range(0, len(words), 8):
        lines.append("    " + " ".join("0x%08x," % w for w in words[i:i + 8]))
    lines.append("};\n")

lines.append("#endif /* VOICE_WHISPER_VULKAN_SPV_H */")
open(out_path, "w").write("\n".join(lines) + "\n")
print("wrote %s (%d modules)" % (out_path, len(names)))
PY
