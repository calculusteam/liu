#!/usr/bin/env python3
"""Regenerate src/core/utf8_marks.h — every zero-width combining mark.

utf8_is_joiner() reads this table, derived from the Unicode database rather
than typed.  A mark missing from it would open its OWN cell instead of folding
into the grapheme before it: Arabic harakat, Hebrew points, every Indic virama
and vowel sign, Thai/Lao/Khmer tone marks, Cyrillic titlo and the Japanese
dakuten U+3099 (which also falls into the CJK width range and would come back
TWO columns wide, so NFD Japanese — what macOS hands back for every filename —
would draw at double width with a floating mark).

    python3 scripts/gen_utf8_marks.py            # rewrite the header
    python3 scripts/gen_utf8_marks.py --check    # verify it is up to date

Categories Mn (nonspacing) and Me (enclosing) only.  Mc (spacing combining
marks) are deliberately NOT here: they advance the pen in every wcwidth
implementation, so folding them into the preceding cell would disagree with
the program on the other end of the pty.  The non-Mn joiners the terminal also
needs (ZWJ, the emoji skin tones, the tag characters) stay hand-written in
utf8.c next to the reason each one is there.
"""
import sys, unicodedata, pathlib

HDR = pathlib.Path(__file__).resolve().parent.parent / "src" / "core" / "utf8_marks.h"

def ranges():
    out = []
    for cp in range(0x300, 0x110000):
        if unicodedata.category(chr(cp)) in ("Mn", "Me"):
            if out and cp == out[-1][1] + 1:
                out[-1][1] = cp
            else:
                out.append([cp, cp])
    return out

EXTRA = [  # joiners that are not Mn/Me — must be in the block map or the
           # pre-filter would reject them before the explicit tests run
    (0x200D, 0x200D),      # ZWJ
    (0x1F3FB, 0x1F3FF),    # emoji skin tones (Sk)
    (0xE0020, 0xE007F),    # tag characters (Cf)
    (0x1160, 0x11FF),      # conjoining Hangul jamo V + T (Lo)
    (0xD7B0, 0xD7C6),
    (0xD7CB, 0xD7FB),
]

BLOCK_SHIFT = 6            # 64 codepoints per block
BLOCK_BITS  = 0x110000 >> BLOCK_SHIFT
BLOCK_BYTES = BLOCK_BITS // 8

def blockmap(rs):
    """One bit per 64-codepoint block: set when the block holds any joiner.

    Rejecting on this is what keeps CJK, Hangul and emoji off the binary
    search, which would otherwise run in front of utf8_char_width's CJK
    ladder for every one of them."""
    bm = bytearray(BLOCK_BYTES)
    for lo, hi in list(rs) + EXTRA:
        for b in range(lo >> BLOCK_SHIFT, (hi >> BLOCK_SHIFT) + 1):
            bm[b >> 3] |= 1 << (b & 7)
    return bm

def render(rs):
    n = sum(hi - lo + 1 for lo, hi in rs)
    bm = blockmap(rs)
    set_blocks = sum(bin(b).count("1") for b in bm)
    bm_body = "\n".join(
        "    " + " ".join("0x%02X," % b for b in bm[i:i + 12])
        for i in range(0, len(bm), 12))
    body = "\n".join(
        "    { 0x%05X, 0x%05X },%s" % (lo, hi, ("  /* %s */" % unicodedata.name(chr(lo), "")) if lo == hi else "")
        for lo, hi in rs)
    return f"""/*
 * Liu — zero-width combining marks (Unicode General_Category Mn + Me).
 *
 * GENERATED by scripts/gen_utf8_marks.py from Unicode {unicodedata.unidata_version}.
 * Do not edit by hand; re-run the script (it has a --check mode) instead.
 *
 * WHY IT IS DERIVED. utf8_is_joiner() carried a hand-written list of ranges,
 * and a hand-written list is exactly as complete as the scripts whoever wrote
 * it was looking at: it covered 272 of these {n} codepoints. Everything it
 * missed opened its own cell instead of folding into the grapheme before it —
 * Arabic harakat, Hebrew points, every Indic virama and vowel sign, Thai, Lao,
 * Khmer, Cyrillic titlo, and U+3099/U+309A, which additionally sit inside the
 * CJK width range and so came back TWO columns wide (NFD Japanese, which is
 * what macOS hands back for every filename, drew at double width with the
 * dakuten floating in its own cell). Sorted and non-overlapping by
 * construction, so utf8_is_joiner binary-searches it.
 */
#ifndef LIU_UTF8_MARKS_H
#define LIU_UTF8_MARKS_H

#include "core/types.h"

typedef struct {{ u32 lo, hi; }} Utf8MarkRange;

/* {len(rs)} ranges, {n} codepoints. */
static const Utf8MarkRange g_utf8_mark_ranges[] = {{
{body}
}};

/* ONE BIT PER {1 << BLOCK_SHIFT}-CODEPOINT BLOCK: set when that block holds any joiner at
 * all — the marks above plus the handful that are not marks (ZWJ, the emoji
 * skin tones, the tag characters, the conjoining Hangul jamo). A clear bit is
 * a definite no in three instructions, which is what keeps CJK, Hangul and
 * emoji off the binary search. Measured with the search in front of
 * utf8_char_width's CJK ladder instead: char_width/cjk -47%,
 * char_width/emoji -35%, display_cols/emoji -38%.
 *
 * {set_blocks} of {BLOCK_BITS} blocks are set, so it rejects {100 - set_blocks * 100 // BLOCK_BITS}% of the space
 * outright, and it is {BLOCK_BYTES} bytes — small enough to stay resident next to
 * the range table. */
#define UTF8_MARK_BLOCK_SHIFT {BLOCK_SHIFT}
#define UTF8_MARK_BLOCK_BITS  {BLOCK_BITS}u

static const u8 g_utf8_mark_blocks[{BLOCK_BYTES}] = {{
{bm_body}
}};

#endif /* LIU_UTF8_MARKS_H */
"""

def main():
    text = render(ranges())
    if "--check" in sys.argv:
        cur = HDR.read_text() if HDR.exists() else ""
        if cur != text:
            print("utf8_marks.h is OUT OF DATE — re-run scripts/gen_utf8_marks.py")
            return 1
        print("utf8_marks.h up to date (Unicode %s)" % unicodedata.unidata_version)
        return 0
    HDR.write_text(text)
    print("wrote %s (%d ranges, Unicode %s)" %
          (HDR, len(ranges()), unicodedata.unidata_version))
    return 0

if __name__ == "__main__":
    sys.exit(main())
